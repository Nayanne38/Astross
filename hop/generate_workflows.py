"""Generate the Apache Hop workflows (.hwf) that orchestrate the Python ETL.

Each Hop action is a SHELL action running one pipeline step, so Hop only sequences, logs and
schedules; all logic stays in Python (`python -m etl.pipelines.run`), which runs standalone too.
Re-run after changing steps:  python hop/generate_workflows.py
"""
from __future__ import annotations

from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent

WORKFLOWS = {
    "etl_full": {
        "description": "Full history: extract (FIRMS archive + API) -> transform/harmonize -> DQ -> load -> ML refresh",
        "mode": "full",
        "steps": [
            ("extract", "-m etl.pipelines.run --mode full --region ${REGION} --steps extract"),
            ("transform", "-m etl.pipelines.run --mode full --region ${REGION} --steps transform"),
            ("data_quality", "-m etl.pipelines.run --mode full --region ${REGION} --steps dq"),
            ("load", "-m etl.pipelines.run --mode full --region ${REGION} --steps load"),
            ("ml_train", "tasks.py train"),
            ("ml_forecast", "tasks.py forecast"),
        ],
    },
    "etl_daily": {
        "description": "Daily incremental: last N days of NRT (MODIS_NRT, VIIRS_NOAA20_NRT, VIIRS_NOAA21_NRT) -> merge -> DQ -> load -> forecast",
        "mode": "incremental",
        "steps": [
            # incremental transform includes its own extract (the NRT window is small)
            ("extract_transform", "-m etl.pipelines.run --mode incremental --region ${REGION} --steps transform"),
            ("data_quality", "-m etl.pipelines.run --mode incremental --region ${REGION} --steps dq"),
            ("load", "-m etl.pipelines.run --mode incremental --region ${REGION} --steps load"),
            ("ml_forecast", "tasks.py forecast"),
        ],
    },
}

START = """    <action>
      <name>Start</name>
      <description/>
      <type>SPECIAL</type>
      <attributes/>
      <start>Y</start>
      <dummy>N</dummy>
      <repeat>N</repeat>
      <schedulerType>0</schedulerType>
      <intervalSeconds>0</intervalSeconds>
      <intervalMinutes>60</intervalMinutes>
      <hour>12</hour>
      <minutes>0</minutes>
      <weekDay>1</weekDay>
      <DayOfMonth>1</DayOfMonth>
      <parallel>N</parallel>
      <xloc>64</xloc>
      <yloc>96</yloc>
      <attributes_hac/>
    </action>
"""

SHELL = """    <action>
      <name>{name}</name>
      <description>{desc}</description>
      <type>SHELL</type>
      <attributes/>
      <filename/>
      <work_directory>${{PROJECT_HOME}}/..</work_directory>
      <arg_from_previous>N</arg_from_previous>
      <exec_per_row>N</exec_per_row>
      <set_logfile>N</set_logfile>
      <logfile/>
      <set_append_logfile>N</set_append_logfile>
      <logext/>
      <add_date>N</add_date>
      <add_time>N</add_time>
      <insertScript>Y</insertScript>
      <script>{script}</script>
      <loglevel>Basic</loglevel>
      <parallel>N</parallel>
      <xloc>{x}</xloc>
      <yloc>96</yloc>
      <attributes_hac/>
    </action>
"""

END = """    <action>
      <name>Success</name>
      <description/>
      <type>SUCCESS</type>
      <attributes/>
      <parallel>N</parallel>
      <xloc>{x}</xloc>
      <yloc>96</yloc>
      <attributes_hac/>
    </action>
"""

HOP = """    <hop>
      <from>{a}</from>
      <to>{b}</to>
      <enabled>Y</enabled>
      <evaluation>Y</evaluation>
      <unconditional>{u}</unconditional>
    </hop>
"""


def build(name: str, spec: dict) -> str:
    actions = [START]
    names = ["Start"]
    for i, (step, args) in enumerate(spec["steps"], 1):
        # ${PYTHON} defaults to the project venv; any failing step (non-zero exit) fails the workflow
        script = f"${{PYTHON}} {args}"
        actions.append(SHELL.format(name=step, desc=escape(f"python {args}"), script=escape(script),
                                    x=64 + 176 * i))
        names.append(step)
    actions.append(END.format(x=64 + 176 * (len(names))))
    names.append("Success")
    hops = "".join(HOP.format(a=a, b=b, u="Y" if a == "Start" else "N") for a, b in zip(names, names[1:]))
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<workflow>
  <name>{name}</name>
  <name_sync_with_filename>Y</name_sync_with_filename>
  <description>{escape(spec['description'])}</description>
  <extended_description>Generated by hop/generate_workflows.py — edit that file, not this one.</extended_description>
  <workflow_version/>
  <created_user>-</created_user>
  <created_date>2026/11/14 00:00:00.000</created_date>
  <modified_user>-</modified_user>
  <modified_date>2026/11/14 00:00:00.000</modified_date>
  <parameters>
    <parameter>
      <name>REGION</name>
      <default_value>matopiba</default_value>
      <description>Region key from config/regions.yaml</description>
    </parameter>
  </parameters>
  <actions>
{''.join(actions)}  </actions>
  <hops>
{hops}  </hops>
  <notepads/>
  <attributes/>
</workflow>
"""


def main() -> None:
    out = HERE / "workflows"
    out.mkdir(exist_ok=True)
    for name, spec in WORKFLOWS.items():
        (out / f"{name}.hwf").write_text(build(name, spec), encoding="utf-8")
        print(f"wrote hop/workflows/{name}.hwf")


if __name__ == "__main__":
    main()
